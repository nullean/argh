			);
	}

	[Test]
	public async Task Sync_prints_the_include_lines_and_mise_hooks_for_new_files()
	{
		var (exit, stdout, _) = await RunAsync("sync", "--run", Run);
		exit.Should().Be(0);
		stdout.Should().Contain("includes = [").And.Contain("-include ").And.Contain("import? '");
		stdout.Should().Contain("postinstall = \"dotnet run build.cs -- __wrappers sync --quiet --run 'dotnet run build.cs --' --out-dir ");

		File.AppendAllText(Path.Combine(_dir, "make.just"), "# edited\n");
		var (again, stdout2, _) = await RunAsync("sync");
		again.Should().Be(0);
		stdout2.Should().Contain("wrote").And.Contain("make.just");
		stdout2.Should().NotContain("postinstall", "the setup hints only follow a newly created file, not a rewritten one");
	}

	[Test]
	public async Task Sync_reuses_the_recorded_run_and_prefix()
	{
		(await RunAsync("sync", "--run", Run, "--prefix", "make")).ExitCode.Should().Be(0);
		var before = FileText("mise-tasks.toml");
		before.Should().Contain("[\"make:schema:update\"]");

		var (exit, stdout, stderr) = await RunAsync("sync");
		exit.Should().Be(0, stderr);
		stdout.Should().Contain("unchanged").And.NotContain("wrote");
		FileText("mise-tasks.toml").Should().Be(before);
		FileText("make.mk").Should().Contain("make/schema/update:");
		FileText("make.just").Should().Contain("@make-schema-update *args:");
	}

	[Test]
	public async Task Sync_without_run_outside_a_file_based_app_exits_2()
	{
		var (exit, _, stderr) = await RunAsync("sync");
		exit.Should().Be(2);
		stderr.Should().Contain("pass --run");
		Directory.Exists(_dir).Should().BeFalse();
	}

	[Test]
	public async Task Sync_only_writes_the_named_wrappers_and_later_syncs_keep_to_them()
	{
		(await RunAsync("sync", "--run", Run, "--only", "mise")).ExitCode.Should().Be(0);
		Directory.GetFiles(_dir).Select(Path.GetFileName).Should().BeEquivalentTo(["mise-tasks.toml"]);

		(await RunAsync("sync")).ExitCode.Should().Be(0);
		Directory.GetFiles(_dir).Select(Path.GetFileName).Should().BeEquivalentTo(["mise-tasks.toml"]);
	}

	[Test]
	public async Task The_recorded_run_comes_from_any_generated_file_not_only_the_selected_ones()
	{
		(await RunAsync("sync", "--run", Run, "--only", "just")).ExitCode.Should().Be(0);

		var (exit, _, stderr) = await RunAsync("check", "--only", "mise");
		exit.Should().Be(1, "the run line is in make.just, so the missing mise file is reported, not an unknown run");
		stderr.Should().Contain("mise-tasks.toml is missing");

		(await RunAsync("sync", "--only", "mise")).ExitCode.Should().Be(0);
		FileText("mise-tasks.toml").Should().Contain("run = \"dotnet run build.cs -- clean\"");
	}

	[Test]
	public async Task Quiet_sync_prints_nothing_when_nothing_changed()
	{
		(await RunAsync("sync", "--run", Run)).ExitCode.Should().Be(0);
		var (exit, stdout, _) = await RunAsync("sync", "--quiet");
		exit.Should().Be(0);
		stdout.Should().BeEmpty();
	}

	[Test]
	public async Task Check_passes_after_sync_and_fails_on_an_edited_or_missing_file()
	{
		(await RunAsync("sync", "--run", Run)).ExitCode.Should().Be(0);
		(await RunAsync("check")).ExitCode.Should().Be(0);

		File.AppendAllText(Path.Combine(_dir, "make.just"), "# edited\n");
		var (stale, _, stderr) = await RunAsync("check");
		stale.Should().Be(1);
		stderr.Should().Contain("make.just is out of date").And.Contain("__wrappers sync");

		File.Delete(Path.Combine(_dir, "make.mk"));
		var (missing, _, stderr2) = await RunAsync("check", "--only", "make");
		missing.Should().Be(1);
		stderr2.Should().Contain("make.mk is missing");
	}

	[Test]
	public async Task Names_that_collide_in_one_wrapper_exit_2()
	{
		var (exit, _, stderr) = await RunAsync<ClashingWrapperBuild>("sync", "--run", Run);
		exit.Should().Be(2);
		stderr.Should().Contain("'schema-update' and 'schema update'").And.Contain("just task 'schema-update'");

		// mise (schema:update) and make (schema/update) keep the two apart.
		(await RunAsync<ClashingWrapperBuild>("sync", "--run", Run, "--only", "mise,make")).ExitCode.Should().Be(0);
	}

	[Test]
	[Arguments("frob")]
	[Arguments("sync --only cake")]
	[Arguments("sync --bogus")]
	public async Task Bad_arguments_exit_2(string args)
	{
		var (exit, _, _) = await RunAsync(args.Split(' '));
		exit.Should().Be(2);
	}

	[Test]
	public async Task Union_apps_answer_wrappers_without_running_a_target()
	{
		var ran = new List<string>();
		var app = new MakeApp<WrapperUnion>("build");
		app.Bind(
			u =>
				u.Value switch
				{
					Clean => app.Target(() => ran.Add("clean")).Description("Delete output"),
					Pack => app.Target(() => ran.Add("pack")),
					_ => throw new InvalidOperationException($"unmapped case {u.Value}")
				}
		);

		var stdout = new StringWriter();
		var oldOut = Console.Out;
		Console.SetOut(stdout);
		int exit;
		try
		{
			exit = await app.RunAsync(["__wrappers", "sync", "--run", Run, "--only", "just", "--out-dir", _dir]);
		}
		finally
		{
			Console.SetOut(oldOut);
		}

		exit.Should().Be(0);
		ran.Should().BeEmpty();
		FileText("make.just")
			.Should()
			.Contain("# Delete output\n[positional-arguments]\n@clean *args:\n    dotnet run build.cs -- clean \"$@\"")
			.And
			.Contain("@pack *args:");
	}

	[Test]
	public async Task Without_a_subcommand_prints_usage_and_exits_2()
	{
		var stderr = new StringWriter();
		var oldErr = Console.Error;
		Console.SetError(stderr);
		try
		{
			(await MakeApp.Execute<WrapperBuild>(["__wrappers"])).Should().Be(2);
		}
		finally
		{
			Console.SetError(oldErr);
		}
		stderr.ToString().Should().Contain("Usage: __wrappers <sync|check>");
	}
}
