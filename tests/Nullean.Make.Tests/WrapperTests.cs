	[Test]
	public async Task Sync_writes_the_make_include()
	{
		var (exit, _, stderr) = await RunAsync("sync", "--run", Run);
		exit.Should().Be(0, stderr);

		FileText("make.mk")
			.Should()
			.Be(
				Header.TrimEnd('\n') +
					"\n" + """
			#
			# make <target> ARGS="--flag value"

			NULLEAN_MAKE_RUN ?= dotnet run build.cs --
			_nullean_make_default_goal := $(.DEFAULT_GOAL)

			.PHONY: clean test schema/update

			# Delete "build" output
			clean:
			{TAB}@$(NULLEAN_MAKE_RUN) clean $(ARGS)

			# Run the tests
			test:
			{TAB}@$(NULLEAN_MAKE_RUN) test $(ARGS)

			# Regenerate the schema
			schema/update:
			{TAB}@$(NULLEAN_MAKE_RUN) schema update $(ARGS)

			.DEFAULT_GOAL := $(_nullean_make_default_goal)

			""".Replace(
					"{TAB}",
					"\t"
				)
			);
	}

	[Test]
	public async Task Sync_writes_the_just_import()
	{
		var (exit, _, stderr) = await RunAsync("sync", "--run", Run);
		exit.Should().Be(0, stderr);

		FileText("make.just")
			.Should()
			.Be(
				Header +
					"""

