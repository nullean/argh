using AwesomeAssertions;
using Nullean.Argh;

namespace Nullean.Make.Tests;

public union WrapperUnion(Clean, Pack);

public record WrapperTestOptions(string? Filter = null, bool NoRestore = false, [Argument] string? Project = null);

public class WrapperBuild : MakeBuild
{
	[Flag("--clean-checkout", "-c", Description = "Skip the clean-checkout guard")]
	public bool CleanCheckout { get; init; }

	public Target Clean =>
		_ => _.Description("Delete \"build\" output").Executes(() =>
		{ });

	public Target<WrapperTestOptions> Test =>
		_ => _
			.Description("Run the tests")
			.DependsOn(Clean)
			.Executes(_ =>
			{ });

	public Target Internal =>
		_ => _.Hidden().Executes(() =>
		{ });

	public class Schema : Namespace
	{
		public Target Update =>
			_ => _.Description("Regenerate the schema").Executes(() =>
			{ });
	}
}

/// <summary><c>schema-update</c> and <c>schema update</c> are distinct targets but the same just recipe name.</summary>
public class KeepBuild : MakeBuild
{
	[Flag("--keep", "-k", Description = "Keep the output")]
	public bool Keep { get; init; }

	public Target Clean =>
		_ => _.Executes(() =>
		{ });
}

public class ClashingWrapperBuild : MakeBuild
{
	public Target SchemaUpdate =>
		_ => _.Executes(() =>
		{ });

	public class Schema : Namespace
	{
		public Target Update =>
			_ => _.Executes(() =>
			{ });
	}
}

[NotInParallel]
public sealed class WrapperTests : IDisposable
{
	private const string Run = "dotnet run build.cs --";
	private readonly string _dir = Path.Combine(Path.GetTempPath(), "make-wrappers-" + Guid.NewGuid().ToString("N"));

	public void Dispose()
	{
		if (Directory.Exists(_dir))
			Directory.Delete(_dir, true);
	}

	private string FileText(string name) => File.ReadAllText(Path.Combine(_dir, name));

	private async Task<(int ExitCode, string Stdout, string Stderr)> RunAsync<TBuild>(params string[] args) where TBuild : MakeBuild, new()
	{
		var stdout = new StringWriter();
		var stderr = new StringWriter();
		var (oldOut, oldErr) = (Console.Out, Console.Error);
		Console.SetOut(stdout);
		Console.SetError(stderr);
		try
		{
			var exit = await MakeApp.Execute<TBuild>(["__wrappers", .. args, "--out-dir", _dir]);
			return (exit, stdout.ToString(), stderr.ToString());
		}
		finally
		{
			Console.SetOut(oldOut);
			Console.SetError(oldErr);
		}
	}

	private Task<(int ExitCode, string Stdout, string Stderr)> RunAsync(params string[] args) => RunAsync<WrapperBuild>(args);

	private const string Header =
		"""
		# Generated by Nullean.Make from 'wrapperbuild'. Do not edit; regenerate with:
		#   dotnet run build.cs -- __wrappers sync
		# run: dotnet run build.cs --

		""";

	[Test]
	public async Task A_build_option_with_the_same_short_name_keeps_it_in_the_mise_include()
	{
		var (exit, _, stderr) = await RunAsync<KeepBuild>("sync", "--run", "dotnet run build.cs --", "--only", "mise");
		exit.Should().Be(0, stderr);
		var text = FileText("mise-tasks.toml");
		text.Should().Contain("flag \"--keep-going\" help=").And.Contain("flag \"-k --keep\"");
	}

