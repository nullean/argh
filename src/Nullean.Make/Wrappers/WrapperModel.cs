using System.Text;
using Nullean.Make.Discovery;

namespace Nullean.Make.Wrappers;

/// <summary>A target or command as a wrapper exposes it.</summary>
internal sealed record WrapperTarget(string[] Route, string? Description, IReadOnlyList<DtoOption> Options);

/// <summary>An option every target accepts: <c>-s</c> and the app's global options.</summary>
internal sealed record WrapperOption(string Long, string? Short, string? Description, bool IsFlag, string TypeName);

/// <summary>What the wrapper emitters need from a <see cref="BuildGraph"/>: the visible targets, the shared options,
/// and the command each wrapper runs.</summary>
internal sealed class WrapperModel
{
	public required string AppName { get; init; }

	/// <summary>The command that runs the build script, e.g. <c>dotnet run build.cs --</c>.</summary>
	public required string Run { get; init; }

	/// <summary>Optional group name put in front of every wrapper task name.</summary>
	public string? Prefix { get; init; }

	public required IReadOnlyList<WrapperTarget> Targets { get; init; }
	public required IReadOnlyList<WrapperOption> Options { get; init; }

	public static WrapperModel From(BuildGraph graph, string run, string? prefix)
	{
		var targets = graph
			.Targets
			.Where(t => !t.Hidden)
			.Select(t => new WrapperTarget(t.Route, OneLine(t.Description), t.DtoType is null ? Array.Empty<DtoOption>() : DtoOptions.Describe(t.DtoType)))
			.ToList();

		// The switches every Make script reads. A build option with the same short name keeps it, as on the command line.
		string? Short(string name) => graph.GlobalOptions.Any(o => o.Short?.TrimStart('-') == name.TrimStart('-')) ? null : name;

		var options = new List<WrapperOption>
		{
			new("--single-target", "-s", "Skip prerequisite deps; run only the body / Composes", true, "bool"),
			new("--graph", null, "Draw what would run and run nothing: tree, mermaid or json", true, "bool"),
			new("--jobs", Short("-j"), "How many targets may run at once (default: one per processor)", false, "int"),
			new("--keep-going", Short("-k"), "After a failure, finish the targets that do not depend on it", true, "bool"),
			new("--output", null, "Output of targets running side by side: prefixed or grouped", false, "string"),
			new("--skip", null, "Leave a target out of the plan, with what only it needed", false, "string"),
		};
		foreach (var o in graph.GlobalOptions)
		{
			var valueType = o.Property?.PropertyType ?? o.ValueType;
			options.Add(
				new WrapperOption(o.Long, o.Short, OneLine(o.Description), o.IsFlag, valueType is null ? "string" : DtoOptions.FriendlyTypeName(valueType))
			);
		}

		return new WrapperModel { AppName = graph.AppName, Run = run, Prefix = prefix, Targets = targets, Options = options };
	}

	/// <summary>The wrapper's name for <paramref name="target"/>: the prefix and route segments joined by <paramref name="separator"/>.</summary>
	public string NameOf(WrapperTarget target, string separator) => string.Join(separator, Prefix is null ? target.Route : [Prefix, .. target.Route]);

	/// <summary>The command line a wrapper runs for <paramref name="target"/>, before the forwarded arguments.</summary>
	public string CommandFor(WrapperTarget target) => $"{Run} {string.Join(" ", target.Route)}";

	/// <summary>The header every generated file starts with, as <c>#</c> comment lines. <see cref="WrapperFiles"/> reads
	/// the <c>run:</c> and <c>prefix:</c> lines back, so a bare <c>__wrappers sync</c> keeps them.</summary>
	public string Header()
	{
		var sb = new StringBuilder();
		sb.Append("# Generated by Nullean.Make from '").Append(AppName).Append("'. Do not edit; regenerate with:\n");
		sb.Append("#   ").Append(Run).Append(" __wrappers sync\n");
		sb.Append("# run: ").Append(Run).Append('\n');
		if (Prefix is not null)
			sb.Append("# prefix: ").Append(Prefix).Append('\n');
		return sb.ToString();
	}

	/// <summary>Collapses whitespace, newlines included, so a description fits one comment or string line.</summary>
	public static string? OneLine(string? text)
	{
		if (string.IsNullOrWhiteSpace(text))
			return null;
		return string.Join(" ", text.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries));
	}
}
