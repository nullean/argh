using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Nullean.Make.Generator;

/// <summary>
/// Finds every <c>new MakeApp&lt;TUnion&gt;(...)</c> and emits a module initializer that registers
/// the union's cases with <c>Nullean.Make.UnionGraph.UnionCaseTable&lt;TUnion&gt;</c>: each case's route,
/// its case type, a factory that wraps a case instance in the outer union, and a factory for the
/// default value <c>MakeApp</c> passes to <c>Bind</c> when it reads the graph.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class UnionCaseGenerator : IIncrementalGenerator
{
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var tables = context
			.SyntaxProvider
			.CreateSyntaxProvider(
				static (node, _) => node is ImplicitObjectCreationExpressionSyntax || node is ObjectCreationExpressionSyntax { Type: var t } && IsMakeAppName(
					t
				),
				static (ctx, ct) => Analyze(ctx.SemanticModel.GetTypeInfo(ctx.Node, ct).Type)
			)
			.Where(static t => t is not null)
			.Collect();

		context.RegisterSourceOutput(tables, static (spc, all) =>
		{
			var seen = new HashSet<string>(StringComparer.Ordinal);
			foreach (var table in all)
			{
				if (table is null || !seen.Add(table.HintName))
					continue;
				spc.AddSource(table.HintName, table.Source);
			}
		});
	}

	private static bool IsMakeAppName(TypeSyntax t) => t switch
	{
		GenericNameSyntax g => g.Identifier.ValueText == "MakeApp",
		QualifiedNameSyntax q => IsMakeAppName(q.Right),
		AliasQualifiedNameSyntax a => IsMakeAppName(a.Name),
		_ => false
	};

	private sealed record UnionTable(string HintName, string Source);

	private static readonly SymbolDisplayFormat Fqn = SymbolDisplayFormat.FullyQualifiedFormat;

	private static UnionTable? Analyze(ITypeSymbol? created)
	{
		if (created is not INamedTypeSymbol { Name: "MakeApp", Arity: 1 } app)
			return null;
		if (app.ContainingNamespace?.ToDisplayString() != "Nullean.Make")
			return null;
		if (app.TypeArguments[0] is not INamedTypeSymbol union || !IsUnion(union))
			return null;

		var unionName = union.ToDisplayString(Fqn);
		var cases = new List<string>();
		var nestedUnions = new List<INamedTypeSymbol>();
		Collect(union, [], [], cases, nestedUnions);

		var sb = new StringBuilder();
		sb.AppendLine("// <auto-generated/>");
		sb.AppendLine("#nullable enable");
		sb.AppendLine("namespace Nullean.Make.Generated");
		sb.AppendLine("{");
		var className = "UnionCases_" + Sanitize(unionName);
		sb.AppendLine($"\tinternal static class {className}");
		sb.AppendLine("\t{");
		sb.AppendLine("\t\t[global::System.Runtime.CompilerServices.ModuleInitializer]");
		sb.AppendLine("\t\tinternal static void Register() =>");
		sb.AppendLine($"\t\t\tglobal::Nullean.Make.UnionGraph.UnionCaseTable<{unionName}>.Register(");
		sb.AppendLine($"\t\t\t\tnew global::Nullean.Make.UnionGraph.UnionCase<{unionName}>[]");
		sb.AppendLine("\t\t\t\t{");
		foreach (var c in cases)
			sb.AppendLine($"\t\t\t\t\t{c},");
		sb.AppendLine("\t\t\t\t},");
		sb.AppendLine("\t\t\t\tstatic u => Leaf(u.Value));");
		sb.AppendLine();
		sb.AppendLine("\t\tprivate static global::System.Type? Leaf(object? value) => value switch");
		sb.AppendLine("\t\t{");
		sb.AppendLine("\t\t\tnull => null,");
		foreach (var nested in nestedUnions)
			sb.AppendLine($"\t\t\t{nested.ToDisplayString(Fqn)} inner => Leaf(inner.Value),");
		sb.AppendLine("\t\t\t_ => value.GetType()");
		sb.AppendLine("\t\t};");
		sb.AppendLine("\t}");
		sb.AppendLine("}");

		return new UnionTable(className + ".g.cs", sb.ToString());
	}

	/// <summary>Walks the union's case constructors; a case that is itself a union adds a route segment.</summary>
	private static void Collect(INamedTypeSymbol union, string[] route, INamedTypeSymbol[] wrappers, List<string> cases, List<INamedTypeSymbol> nestedUnions)
	{
		foreach (var ctor in UnionCtors(union))
		{
			if (ctor.Parameters[0].Type is not INamedTypeSymbol caseType)
				continue;
			string[] caseRoute = [.. route, ToKebabCase(caseType.Name)];
			INamedTypeSymbol[] caseWrappers = [.. wrappers, union];
			if (IsUnion(caseType))
			{
				nestedUnions.Add(caseType);
				Collect(caseType, caseRoute, caseWrappers, cases, nestedUnions);
				continue;
			}

			var caseName = caseType.ToDisplayString(Fqn);
			var routeLiteral = string.Join(", ", caseRoute.Select(s => "\"" + s + "\""));
			cases.Add(
				$"new(new string[] {{ {routeLiteral} }}, typeof({caseName}), " + $"static c => {Wrap(caseWrappers, $"({caseName})c")}, " +
					$"static () => {Wrap(caseWrappers, DefaultInstance(caseType, caseName))})"
			);
		}
	}

	/// <summary><c>new Outer(new Inner(expr))</c>, outermost union first.</summary>
	private static string Wrap(INamedTypeSymbol[] wrappers, string expr)
	{
		for (var i = wrappers.Length - 1; i >= 0; i--)
			expr = $"new {wrappers[i].ToDisplayString(Fqn)}({expr})";
		return expr;
	}

	/// <summary>
	/// A case value for reading the graph: the widest public constructor, passing <c>default!</c> for
	/// every parameter without a default value. Value-type cases use <c>default</c>.
	/// </summary>
	private static string DefaultInstance(INamedTypeSymbol caseType, string caseName)
	{
		var ctor = caseType
			.InstanceConstructors
			.Where(c => c.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal)
			.Where(c => !(c.Parameters.Length == 1 && SymbolEqualityComparer.Default.Equals(c.Parameters[0].Type, caseType)))
			.OrderByDescending(c => c.Parameters.Length)
			.FirstOrDefault();
		if (ctor is null)
			return caseType.IsValueType
				? $"default({caseName})"
				: $"throw new global::System.InvalidOperationException(\"{caseType.Name} has no accessible constructor.\")";
		var args = ctor.Parameters.Where(p => !p.HasExplicitDefaultValue && !p.IsParams).Select(p => $"@{p.Name}: default!");
		return $"new {caseName}({string.Join(", ", args)})";
	}

	private static IEnumerable<IMethodSymbol> UnionCtors(INamedTypeSymbol t) =>
		t.InstanceConstructors.Where(c => c.DeclaredAccessibility == Accessibility.Public && c.Parameters.Length == 1);

	/// <summary>Same check as the Argh generator: the lowered <c>IUnion</c> marker, <c>[Union]</c>, or the structural shape.</summary>
	private static bool IsUnion(INamedTypeSymbol t)
	{
		if (t.AllInterfaces.Any(i => i.Name == "IUnion"))
			return true;
		if (t.GetAttributes().Any(a => a.AttributeClass?.Name is "UnionAttribute" or "Union"))
			return true;
		return t.TypeKind == TypeKind.Struct && t
			.GetMembers("Value")
			.OfType<IPropertySymbol>()
			.Any(p => p.Type.SpecialType == SpecialType.System_Object) && UnionCtors(t).Any();
	}

	internal static string ToKebabCase(string name)
	{
		var sb = new StringBuilder();
		for (var i = 0; i < name.Length; i++)
		{
			var c = name[i];
			if (char.IsUpper(c) && i > 0)
				sb.Append('-');
			sb.Append(char.ToLowerInvariant(c));
		}
		return sb.ToString();
	}

	private static string Sanitize(string name)
	{
		var sb = new StringBuilder();
		foreach (var c in name.Replace("global::", ""))
			sb.Append(char.IsLetterOrDigit(c) ? c : '_');
		return sb.ToString();
	}
}
